/** Reads src/data/destinations.ts without needing a TypeScript compiler. */
const loadDestinations = () => {
  const tsPath = path.resolve(__dirname, '../src/data/destinations.ts');
  const tempPath = path.join(os.tmpdir(), `sbf-destinations-${process.pid}.cjs`);
  try {
    const lines = fs.readFileSync(tsPath, 'utf8').split('\n');
    const start = lines.findIndex((l) => l.includes('export const destinations'));
    if (start === -1) throw new Error('Could not find destinations array');
    let content = lines.slice(start).join('\n').replace('export const destinations: Destination[] =', 'const destinations =');
    const iconMapIndex = content.indexOf('export const destinationIconMap');
    if (iconMapIndex !== -1) content = content.slice(0, iconMapIndex);
    content += '\nmodule.exports = { destinations };\n';
    fs.writeFileSync(tempPath, content, 'utf8');
    return require(tempPath).destinations;
  } finally {
    if (fs.existsSync(tempPath)) fs.unlinkSync(tempPath);
  }
};

/** Blog SEO: existing posts (src/lib/blogSeo.js) + new guides (src/lib/blogPosts.js). */
const loadBlogs = async (destinations) => {
  const base = (await import(pathToFileURL(path.resolve(__dirname, '../src/lib/blogSeo.js')).href)).blogSeo;
  const seo = await import(pathToFileURL(path.resolve(__dirname, '../src/lib/seoShared.js')).href);
  const extra = await import(pathToFileURL(path.resolve(__dirname, '../src/lib/blogPosts.js')).href);
  return { ...base, ...extra.buildNewBlogSeo({ destinations, year: seo.seasonYear() }) };
};

